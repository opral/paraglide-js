import { createHash } from "node:crypto";
import path from "node:path";
import type { ViteDevServer, Plugin } from "vite";
import type { Program } from "estree";
import { createVitePlugin } from "unplugin";
import { unpluginFactory, type ParaglidePluginOptions } from "./unplugin.js";
import { toSafeModuleId } from "../compiler/safe-module-id.js";
import { shareRuntimeTypes } from "../compiler/emit-ts-declarations.js";
import { rewriteVirtualMessageImports } from "./virtual-message-imports.js";

export function virtualMessagePrefix(directory: string) {
	return `virtual:paraglide/${createHash("sha256").update(path.resolve(directory)).digest("hex").slice(0, 16)}/`;
}

/** Aggregate direct-emitter declarations without parsing application JavaScript. */
export function virtualMessageOutput(
	output: Record<string, string>,
	directory: string
) {
	const id = virtualMessagePrefix(directory) + "messages/_index.js";
	const localizedString =
		'export type LocalizedString = import("../runtime.js").LocalizedString;';
	const declarations = Object.entries(output)
		.filter(
			([name]) =>
				name.startsWith("messages/") &&
				name.endsWith(".d.ts") &&
				name !== "messages/_index.d.ts"
		)
		.map(([name, code]) => {
			// The public disk barrel uses export *, which excludes a leaf's
			// default value. Keep its input type but preserve that value surface.
			if (name === `messages/${toSafeModuleId("default")}.d.ts`)
				code = code.replace(
					/^declare const [A-Za-z_$][\w$]*:[^\n]*\r?\nexport \{ [A-Za-z_$][\w$]* as "default" \};\r?$/m,
					""
				);
			return code.replace(
				/^export type LocalizedString = import\("\.\.\/runtime\.js"\)\.LocalizedString;\r?$/m,
				""
			);
		})
		.join("\n");
	const disk: Record<string, string> = {};
	const implementations: Record<string, string> = {};
	for (const [name, code] of Object.entries(output)) {
		if (
			name === "messages/package.json" ||
			(name.startsWith("messages/") && name.endsWith(".d.ts"))
		)
			continue;
		if (
			name.endsWith(".js") &&
			(name === "messages.js" || name.startsWith("messages/"))
		)
			implementations[name] = code;
		else disk[name] = code;
	}
	const facade =
		"// Generated by Paraglide. Message implementations are virtual modules.\n// The Paraglide Vite plugin supplies them in development and production builds.\n" +
		output["messages.js"]!.replaceAll(
			"'./messages/_index.js'",
			JSON.stringify(id)
		);
	disk["messages.js"] = facade;
	implementations["messages.js"] = facade;
	disk["messages.d.ts"] =
		'/// <reference path="./messages.virtual.d.ts" />\n' +
		`export * from ${JSON.stringify(id)};\nexport * as m from ${JSON.stringify(id)};\n`;
	disk["messages.virtual.d.ts"] =
		`declare module ${JSON.stringify(id)} {\n` +
		(localizedString + "\n" + shareRuntimeTypes(declarations))
			.replaceAll('import("../runtime.js")', 'import("./runtime.js")')
			.replace(/^declare const /gm, "const ") +
		"\n}\n";
	return { disk, implementations };
}

export function virtualMessages(
	directory: string,
	initial: Record<string, string>
) {
	const publicPrefix = virtualMessagePrefix(directory);
	const prefix = "\0" + publicPrefix;
	let files = initial;
	let server: ViteDevServer | undefined;
	const virtualName = (id: string | undefined) =>
		id?.startsWith(prefix) ? id!.slice(prefix.length) : undefined;
	const relativeName = (id: string) => {
		const absolute = path.resolve(id);
		const relative = path
			.relative(directory, absolute)
			.split(path.sep)
			.join("/");
		return relative.startsWith("../") ? undefined : relative;
	};
	return {
		name: "paraglide-virtual-message-transport",
		enforce: "pre" as const,
		configureServer(value: ViteDevServer) {
			server = value;
		},
		resolveId(source: string, importer?: string) {
			if (source.startsWith(publicPrefix)) {
				const name = source.slice(publicPrefix.length);
				return Object.hasOwn(files, name) ? prefix + name : null;
			}
			const ownName = virtualName(source);
			if (ownName !== undefined)
				return Object.hasOwn(files, ownName) ? source : null;
			const parent = virtualName(importer);
			let absolute;
			if (source.startsWith(".")) {
				absolute = path.resolve(
					parent !== undefined
						? path.dirname(path.join(directory, parent))
						: path.dirname(importer ?? directory),
					source
				);
			} else if (path.isAbsolute(source)) absolute = source;
			else return null;
			const name = relativeName(absolute);
			if (name !== undefined) {
				if (Object.hasOwn(files, name)) return prefix + name;
				if (!path.extname(name) && Object.hasOwn(files, name + ".js"))
					return prefix + name + ".js";
			}
			if (parent !== undefined && source.startsWith(".")) return absolute;
			return null;
		},
		load(id: string) {
			const name = virtualName(id);
			if (name !== undefined && Object.hasOwn(files, name))
				return {
					code:
						name === "messages.js"
							? files[name]!.replaceAll(
									"'./messages/_index.js'",
									JSON.stringify(publicPrefix + "messages/_index.js")
								)
							: files[name]!,
					map: null,
					moduleSideEffects: false,
				};
			return null;
		},
		api: {
			// Called after a successful compiler publication.
			update(next: Record<string, string>) {
				const changed = [
					...new Set([...Object.keys(files), ...Object.keys(next)]),
				].filter((name) => files[name] !== next[name]);
				files = next;
				if (server && changed.length)
					reloadEnvironments(
						server,
						changed.map((name) => prefix + name)
					);
				return changed;
			},
		},
	};
}

/**
 * Invalidates the modules with these ids and their importers, or every module,
 * in each environment of the dev server, and reloads the environment. Each
 * Vite 6+ environment has its own module graph and hot channel; the server's
 * `moduleGraph` and `ws` reach only the client and SSR environments, which are
 * the only ones Vite 5 has.
 */
function reloadEnvironments(server: ViteDevServer, ids?: string[]) {
	if (!server.environments) {
		invalidate(server.moduleGraph, ids);
		server.ws.send({ type: "full-reload" });
		return;
	}
	for (const environment of Object.values(server.environments)) {
		invalidate(environment.moduleGraph, ids);
		environment.hot.send({ type: "full-reload" });
	}
}

function invalidate<Module extends { importers: Set<Module> }>(
	moduleGraph: {
		getModuleById(id: string): Module | undefined;
		invalidateModule(module: Module): void;
		invalidateAll(): void;
	},
	ids: string[] | undefined
) {
	if (!ids) {
		moduleGraph.invalidateAll();
		return;
	}
	// Invalidate every importer: re-export barrels must not keep stale
	// transformed bindings when a message's exports change.
	const seen = new Set<Module>();
	const invalidateWithImporters = (module: Module | undefined) => {
		if (!module || seen.has(module)) return;
		seen.add(module);
		for (const importer of module.importers) invalidateWithImporters(importer);
		moduleGraph.invalidateModule(module);
	};
	for (const id of ids) invalidateWithImporters(moduleGraph.getModuleById(id));
}

export function createVirtualMessagesPlugins(
	compilerOptions: ParaglidePluginOptions,
	devErrorResponse?: boolean
): Plugin[] {
	let transport: ReturnType<typeof virtualMessages> | undefined;
	let directory: string | undefined;
	let server: ViteDevServer | undefined;
	let messages: ReadonlyMap<string, string> = new Map();
	const virtual: Plugin = {
		name: "paraglide-virtual-messages",
		enforce: "pre",
		configureServer(value) {
			server = value;
		},
		async resolveId(source, importer) {
			const direct = transport?.resolveId(source, importer);
			if (direct || !transport || !/(?:^|\/)messages(?:\.js)?$/.test(source))
				return direct;
			const resolved = await this.resolve(source, importer, { skipSelf: true });
			return resolved ? transport.resolveId(resolved.id, importer) : null;
		},
		load(id) {
			return transport?.load(id);
		},
	};
	const optimize: Plugin = {
		name: "paraglide-virtual-message-imports",
		enforce: "post",
		async transform(code, id) {
			if (
				!transport ||
				!directory ||
				id.includes("/node_modules/") ||
				id.startsWith("\0") ||
				!code.includes("messages")
			)
				return null;
			let ast: Program;
			try {
				ast = this.parse(code) as unknown as Program;
			} catch {
				return null;
			}
			const sources = new Set<string>();
			const rootId = "\0" + virtualMessagePrefix(directory) + "messages.js";
			for (const statement of ast.body) {
				if (
					statement.type !== "ImportDeclaration" ||
					typeof statement.source.value !== "string" ||
					!/(?:^|\/)messages(?:\.js)?$/.test(statement.source.value)
				)
					continue;
				const resolved = await this.resolve(statement.source.value, id, {
					skipSelf: true,
				});
				if (resolved?.id === rootId) sources.add(statement.source.value);
			}
			if (!sources.size) return null;
			return rewriteVirtualMessageImports({
				code,
				id,
				ast,
				imports: sources,
				messages,
			});
		},
	};
	const compiler = createVitePlugin<ParaglidePluginOptions>((options, meta) =>
		unpluginFactory(options, meta, {
			devErrorResponse,
			outputStructure: "virtual-modules",
			emitTsDeclarations: (options) =>
				options.outputStructure === "virtual-modules",
			validateOptions(options) {
				if (options.outputStructure !== "virtual-modules") return;
				if (options.emitTsDeclarations === false)
					throw new Error(
						'outputStructure: "virtual-modules" requires emitTsDeclarations: true. Enable declarations or select "message-modules" or "locale-modules" for physical output.'
					);
				if ((options.messageModuleSize ?? 1) !== 1)
					throw new Error(
						'outputStructure: "virtual-modules" requires messageModuleSize: 1'
					);
			},
			getOutputTransform(options) {
				if (options.outputStructure !== "virtual-modules") {
					if (!transport) return undefined;
					return (output) => ({
						output,
						onPublished() {
							transport = undefined;
							directory = undefined;
							messages = new Map();
							if (server) reloadEnvironments(server);
						},
					});
				}
				return (output, nextDirectory, ids) => {
					const packed = virtualMessageOutput(output, nextDirectory);
					const prefix = virtualMessagePrefix(nextDirectory);
					const nextMessages = new Map(
						ids
							.filter((id) => id !== "default")
							.map((id) => [
								id,
								prefix + "messages/" + toSafeModuleId(id) + ".js",
							])
					);
					return {
						output: packed.disk,
						onPublished() {
							messages = nextMessages;
							if (!transport || directory !== nextDirectory) {
								directory = nextDirectory;
								transport = virtualMessages(directory, packed.implementations);
								if (server) {
									transport.configureServer(server);
									reloadEnvironments(server);
								}
							} else transport.api.update(packed.implementations);
						},
					};
				};
			},
		})
	);
	return [virtual, compiler(compilerOptions) as Plugin, optimize];
}
